def render(draft=None, template: bytes | None = None, **settings) -> Document:
    data = render_minutes_docx(draft or samples.draft(), PresentationSettings(**settings), template)
    return docx.Document(io.BytesIO(data))


def body_text(doc) -> list[str]:
    return [p.text for p in doc.paragraphs]


def commented_text(doc) -> dict[str, str]:
    """Comment id -> the exact text between its range start and end."""
    spans: dict[str, str] = {}
    open_ids: set[str] = set()
    for el in doc.element.body.iter():
        if el.tag == qn("w:commentRangeStart"):
            open_ids.add(el.get(qn("w:id")))
        elif el.tag == qn("w:commentRangeEnd"):
            open_ids.discard(el.get(qn("w:id")))
        elif el.tag == qn("w:t"):
            for cid in open_ids:
                spans[cid] = spans.get(cid, "") + (el.text or "")
    return spans


def test_structure_follows_the_agenda() -> None:
    text = body_text(render())
    assert text[0].startswith("Minutes of a meeting of the Board of Trustees")
    assert text[1] == "Draft"
    assert "4 Roof replacement programme: contract award" in text
    assert "The Board approved phase one only, capped at £1.2 million." in text


def test_question_is_a_comment_on_the_exact_phrase() -> None:
    doc = render()
    comments = list(doc.comments)
    assert [c.text for c in comments] == ["Who was asked to write to tenants about the roof works?"]
    assert comments[0].author == "DESS Minutes"
    assert list(commented_text(doc).values()) == ["phase one only"]
    # The question never appears in the minutes themselves.
    assert not any("Who was asked" in t for t in body_text(doc))


def test_heading_and_meeting_anchors() -> None:
    draft = samples.draft()
    draft.questions = [
        ClarificationQuestion(
            question_id="Q1", requirement_ids=[], anchor_kind=AnchorKind.ITEM_HEADING,
            item_ref="3", paragraph_id=None, anchor_text=None, question="Was a paper tabled?",
        ),
        ClarificationQuestion(
            question_id="Q2", requirement_ids=[], anchor_kind=AnchorKind.MEETING_HEADING,
            item_ref=None, paragraph_id=None, anchor_text=None, question="What time did it start?",
        ),
    ]  # fmt: skip
    spans = commented_text(render(draft))
    assert sorted(spans.values()) == [
        "3 Chief Executive's report",
        "Minutes of a meeting of the Board of Trustees of Northbridge Housing Trust",
    ]


def test_missing_anchor_falls_back_to_item_heading() -> None:
    draft = samples.draft()
    draft.questions[0].anchor_text = "text that is not there"
    assert list(commented_text(render(draft)).values()) == [
        "4 Roof replacement programme: contract award"
    ]


def test_presentation_settings() -> None:
    draft = samples.draft()
    draft.actions = []
    doc = render(
        draft,
        status_label=None,
        numbering=NumberingScheme.MINUTE_REFERENCE,
        minute_reference_prefix="B/26/",
        paragraph_numbering=ParagraphNumbering.ITEM_DECIMAL,
        attendance_layout=AttendanceLayout.PARAGRAPH,
    )
    text = body_text(doc)
    assert "Draft" not in text
    assert "B/26/04 Roof replacement programme: contract award" in text
    assert "B/26/04.2 The Board approved phase one only, capped at £1.2 million." in text
    assert "Apologies: Daniel" in text


def test_iso_dates_are_formatted() -> None:
    draft = samples.draft()
    draft.header.meeting_date = "2026-03-12"
    assert "12 March 2026" in body_text(render(draft))


def test_action_table() -> None:
    draft = samples.draft()
    draft.actions = [
        ActionEntry(action_id="AC1", text="Report on phase two", owner="Finance Director",
                    due=None, paragraph_id="4.p2")
    ]  # fmt: skip
    doc = render(draft, action_presentation=ActionPresentation.INLINE_AND_TABLE)
    rows = [[c.text for c in r.cells] for r in doc.tables[0].rows]
    assert rows == [["Action", "Owner", "Due"], ["Report on phase two", "Finance Director", ""]]


def test_no_approval_or_signature_blocks() -> None:
    text = " ".join(body_text(render())).lower()
    for phrase in ("signed", "signature", "approved by the chair", "generated by", "ai "):
        assert phrase not in text


def template_bytes(with_marker: bool) -> bytes:
    doc = docx.Document()
    doc.sections[0].header.paragraphs[0].text = "Northbridge letterhead"
    doc.add_paragraph("Cover note")
    if with_marker:
        doc.add_paragraph(MARKER)
    doc.add_paragraph("Footer note")
    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


def test_template_marker_is_replaced() -> None:
    doc = render(template=template_bytes(with_marker=True))
    text = body_text(doc)
    assert text[0] == "Cover note"
    assert text[-1] == "Footer note"
    assert MARKER not in text
    assert any(t.startswith("4 Roof") for t in text)
    assert doc.sections[0].header.paragraphs[0].text == "Northbridge letterhead"
    assert len(list(doc.comments)) == 1


def test_template_without_marker_keeps_header_but_replaces_body() -> None:
    doc = render(template=template_bytes(with_marker=False))
    text = body_text(doc)
    assert "Cover note" not in text
    assert text[0].startswith("Minutes of a meeting")
    assert doc.sections[0].header.paragraphs[0].text == "Northbridge letterhead"
